let lang = 'zh';
try { lang = localStorage.getItem('editor-lang') || 'zh'; } catch { /* storage unavailable */ }

export const getLang = () => lang;
export function setLang(l) {
  lang = l;
  try { localStorage.setItem('editor-lang', l); } catch { /* ignore */ }
  document.documentElement.lang = l === 'zh' ? 'zh-CN' : 'en';
}

export function t(key, vars) {
  const entry = S[key];
  let s = entry ? entry[lang === 'zh' ? 0 : 1] : key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(v);
  return s;
}
